-- An exceptional Administrator action: remove a citation from operational tables
-- while retaining the entire case, payment ledger, disputes and evidence in a
-- restricted, append-only-by-policy archive. This is not an erasure of records.
-- Never grant direct access to this archive or RPC to browser roles.

CREATE TABLE IF NOT EXISTS private.tvtms_archived_citation_deletions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_ticket_id bigint NOT NULL,
  citation_number text NOT NULL,
  archived_by bigint NOT NULL,
  reason text NOT NULL,
  snapshot jsonb NOT NULL,
  snapshot_digest text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT archive_reason_length CHECK (length(btrim(reason)) BETWEEN 10 AND 500),
  CONSTRAINT archive_digest_matches CHECK (snapshot_digest = md5(snapshot::text))
);
REVOKE ALL ON TABLE private.tvtms_archived_citation_deletions FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.tvtms_ticket_admin_archived_delete(
  p_id bigint, p_user_id bigint, p_ticket_number text, p_reason text, p_confirmation text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $archive$
DECLARE
  v_ticket public.tickets%rowtype;
  v_actor_role text;
  v_actor_status text;
  v_snapshot jsonb;
  v_archive_id bigint;
  v_audit_id bigint;
  v_deleted integer;
  v_payments integer;
  v_disputes integer;
  v_evidence integer;
BEGIN
  IF p_confirmation IS DISTINCT FROM 'ARCHIVE AND DELETE' THEN
    RETURN public.tvtms_ticket_error('ARCHIVE_CONFIRMATION_REQUIRED',
      'Type ARCHIVE AND DELETE to confirm protected record removal.',409);
  END IF;
  IF length(btrim(coalesce(p_reason,''))) NOT BETWEEN 10 AND 500 THEN
    RETURN public.tvtms_ticket_error('VALIDATION_ERROR',
      'Provide an accountable reason of 10 to 500 characters.',400);
  END IF;
  SELECT role,status INTO v_actor_role,v_actor_status FROM public.users WHERE id=p_user_id;
  IF v_actor_role IS DISTINCT FROM 'admin' OR v_actor_status IS DISTINCT FROM 'active' THEN
    RETURN public.tvtms_ticket_error('ADMIN_REQUIRED','An active Administrator is required.',403);
  END IF;
  SELECT * INTO v_ticket FROM public.tickets WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN public.tvtms_ticket_error('TICKET_NOT_FOUND','Citation not found.',404);
  END IF;
  IF v_ticket.ticket_number IS DISTINCT FROM p_ticket_number THEN
    RETURN public.tvtms_ticket_error('DELETE_CONFIRMATION_REQUIRED',
      'Type the exact citation number before deleting.',409);
  END IF;
  -- Lock related rows so the archived values match those being deleted.
  PERFORM 1 FROM public.payments WHERE ticket_id=p_id FOR UPDATE;
  PERFORM 1 FROM public.disputes WHERE ticket_id=p_id FOR UPDATE;
  PERFORM 1 FROM public.evidence WHERE ticket_id=p_id FOR UPDATE;
  PERFORM 1 FROM public.public_dispute_verifications WHERE ticket_id=p_id FOR UPDATE;
  PERFORM 1 FROM public.ticket_email_notifications WHERE ticket_id=p_id FOR UPDATE;
  PERFORM 1 FROM public.ticket_status_history WHERE ticket_id=p_id FOR UPDATE;
  PERFORM 1 FROM public.ticket_violations WHERE ticket_id=p_id FOR UPDATE;

  v_snapshot=jsonb_build_object(
    'archiveVersion',1,
    'ticket',to_jsonb(v_ticket),
    'payments',(SELECT coalesce(jsonb_agg(to_jsonb(p) ORDER BY p.id),'[]'::jsonb) FROM public.payments p WHERE p.ticket_id=p_id),
    'disputes',(SELECT coalesce(jsonb_agg(to_jsonb(d) ORDER BY d.id),'[]'::jsonb) FROM public.disputes d WHERE d.ticket_id=p_id),
    'evidence',(SELECT coalesce(jsonb_agg(to_jsonb(e) ORDER BY e.id),'[]'::jsonb) FROM public.evidence e WHERE e.ticket_id=p_id),
    'publicDisputeVerifications',(SELECT coalesce(jsonb_agg(to_jsonb(v) ORDER BY v.id),'[]'::jsonb) FROM public.public_dispute_verifications v WHERE v.ticket_id=p_id),
    'emailNotifications',(SELECT coalesce(jsonb_agg(to_jsonb(e) ORDER BY e.id),'[]'::jsonb) FROM public.ticket_email_notifications e WHERE e.ticket_id=p_id),
    'statusHistory',(SELECT coalesce(jsonb_agg(to_jsonb(h) ORDER BY h.id),'[]'::jsonb) FROM public.ticket_status_history h WHERE h.ticket_id=p_id),
    'violations',(SELECT coalesce(jsonb_agg(to_jsonb(v) ORDER BY v.id),'[]'::jsonb) FROM public.ticket_violations v WHERE v.ticket_id=p_id),
    'notifications',(SELECT coalesce(jsonb_agg(to_jsonb(n) ORDER BY n.id),'[]'::jsonb)
        FROM public.notifications n
        WHERE (n.reference_type='ticket' AND n.reference_id=p_id)
           OR (n.reference_type='dispute' AND n.reference_id IN (SELECT d.id FROM public.disputes d WHERE d.ticket_id=p_id)))
  );
  v_payments=jsonb_array_length(v_snapshot->'payments');
  v_disputes=jsonb_array_length(v_snapshot->'disputes');
  v_evidence=jsonb_array_length(v_snapshot->'evidence');

  INSERT INTO private.tvtms_archived_citation_deletions
    (original_ticket_id,citation_number,archived_by,reason,snapshot,snapshot_digest)
  VALUES(p_id,v_ticket.ticket_number,p_user_id,btrim(p_reason),v_snapshot,md5(v_snapshot::text))
  RETURNING id INTO v_archive_id;
  IF v_archive_id IS NULL THEN
    RAISE EXCEPTION 'Protected deletion aborted: archive was not saved';
  END IF;

  -- Public audit history retains metadata, not duplicated sensitive case data.
  INSERT INTO public.audit_logs(user_id,action,entity_type,entity_id,metadata)
  VALUES(p_user_id,'TICKET_ARCHIVED_AND_REMOVED','tickets',p_id,
    jsonb_build_object('ticketNumber',v_ticket.ticket_number,'archiveId',v_archive_id,
      'reason',btrim(p_reason),'snapshotDigest',md5(v_snapshot::text),
      'payments',v_payments,'disputes',v_disputes,'evidence',v_evidence)::text)
  RETURNING id INTO v_audit_id;
  IF v_audit_id IS NULL THEN RAISE EXCEPTION 'Protected deletion aborted: audit log missing'; END IF;

  DELETE FROM public.notifications
  WHERE (reference_type='ticket' AND reference_id=p_id)
     OR (reference_type='dispute' AND reference_id IN (SELECT id FROM public.disputes WHERE ticket_id=p_id));
  DELETE FROM public.payments WHERE ticket_id=p_id;
  DELETE FROM public.disputes WHERE ticket_id=p_id;
  DELETE FROM public.ticket_email_notifications WHERE ticket_id=p_id;
  DELETE FROM public.public_dispute_verifications WHERE ticket_id=p_id;
  DELETE FROM public.evidence WHERE ticket_id=p_id;
  DELETE FROM public.ticket_status_history WHERE ticket_id=p_id;
  DELETE FROM public.ticket_violations WHERE ticket_id=p_id;
  DELETE FROM public.tickets WHERE id=p_id;
  GET DIAGNOSTICS v_deleted=ROW_COUNT;
  IF v_deleted<>1 THEN RAISE EXCEPTION 'Protected deletion failed and transaction was rolled back'; END IF;
  RETURN jsonb_build_object('ticketNumber',v_ticket.ticket_number,'authorizationAuditId',v_audit_id,
    'archiveId',v_archive_id,'archivedPayments',v_payments,'archivedDisputes',v_disputes,
    'archivedEvidence',v_evidence,'archivedAndRemoved',true);
END
$archive$;

REVOKE ALL ON FUNCTION public.tvtms_ticket_admin_archived_delete(bigint,bigint,text,text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.tvtms_ticket_admin_archived_delete(bigint,bigint,text,text,text) TO service_role;
COMMENT ON FUNCTION public.tvtms_ticket_admin_archived_delete(bigint,bigint,text,text,text) IS
'Service-role-only administrative archive/removal with typed confirmation, full case preservation and atomic audit. Never call from public/browser code.';
