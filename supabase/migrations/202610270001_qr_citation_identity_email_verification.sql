-- QR citation identity is revealed only after a fresh email code is verified.
-- No existing tickets or identity snapshots are rewritten.
-- Service-role only; no browser/Data API access to private challenges.
create schema if not exists private;

create table if not exists private.tvtms_qr_identity_challenges (
 id bigint generated by default as identity primary key,
 ticket_id bigint not null references public.tickets(id) on delete cascade,
 token_hash char(64) not null unique,
 code_hash char(64) not null,
 requester_hash char(64) not null,
 status text not null default 'pending' check(status in ('pending','used','expired','locked')),
 delivery_status text not null default 'pending' check(delivery_status in ('pending','accepted','failed')),
 attempts_remaining smallint not null default 5 check(attempts_remaining between 0 and 5),
 requested_at timestamptz not null default current_timestamp,
 delivered_at timestamptz,
 expires_at timestamptz not null,
 used_at timestamptz
);
create index if not exists tvtms_qr_identity_ticket_recent
 on private.tvtms_qr_identity_challenges(ticket_id, requested_at desc);
create index if not exists tvtms_qr_identity_requester_recent
 on private.tvtms_qr_identity_challenges(requester_hash, requested_at desc);
alter table private.tvtms_qr_identity_challenges enable row level security;
revoke all on private.tvtms_qr_identity_challenges from public, anon, authenticated, service_role;
grant usage on schema private to service_role;
grant select, insert, update on private.tvtms_qr_identity_challenges to service_role;
grant usage, select on sequence private.tvtms_qr_identity_challenges_id_seq to service_role;

create or replace function public.tvtms_qr_identity_request(
 p_ticket text,p_token_hash text,p_code_hash text,p_requester_hash text
) returns jsonb language plpgsql security invoker set search_path='' as $fn$
declare
 citation record;
 recipient text;
 last_requested timestamptz;
 ticket_hour integer;
 requester_hour integer;
begin
 if p_ticket is null or p_ticket !~ '^[A-Z0-9][A-Z0-9/-]{0,29}$'
   or coalesce(p_token_hash,'') !~ '^[0-9a-f]{64}$'
   or coalesce(p_code_hash,'') !~ '^[0-9a-f]{64}$'
   or coalesce(p_requester_hash,'') !~ '^[0-9a-f]{64}$' then
  return jsonb_build_object('errorCode','VALIDATION_ERROR','message','Invalid verification request.','statusCode',400);
 end if;
 -- Lock ticket so concurrent requests cannot bypass the per-citation cooldown.
 select t.id,t.ticket_number,t.citation_version,t.driver_email_at_issue,t.owner_email_at_issue
  into citation from public.tickets t where upper(trim(t.ticket_number))=p_ticket for update of t;
 if not found then
  return jsonb_build_object('errorCode','IDENTITY_VERIFICATION_UNAVAILABLE',
   'message','Email verification is unavailable for this citation. Contact the issuing office.','statusCode',409);
 end if;
 recipient:=lower(trim(case when citation.citation_version=2
  then coalesce(citation.driver_email_at_issue,'') else coalesce(citation.owner_email_at_issue,'') end));
 -- Never fall back to mutable vehicle/owner email data.
 if recipient !~* '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$' then
  return jsonb_build_object('errorCode','IDENTITY_VERIFICATION_UNAVAILABLE',
   'message','Email verification is unavailable for this citation. Contact the issuing office.','statusCode',409);
 end if;
 select max(requested_at) into last_requested from private.tvtms_qr_identity_challenges
   where ticket_id=citation.id;
 if last_requested is not null and last_requested>current_timestamp-interval '90 seconds' then
  return jsonb_build_object('errorCode','IDENTITY_COOLDOWN',
   'message','Please wait before requesting another verification code.','statusCode',429,'retryAfter',90);
 end if;
 select count(*) into ticket_hour from private.tvtms_qr_identity_challenges
   where ticket_id=citation.id and requested_at>current_timestamp-interval '1 hour';
 select count(*) into requester_hour from private.tvtms_qr_identity_challenges
   where requester_hash=p_requester_hash and requested_at>current_timestamp-interval '1 hour';
 if ticket_hour>=4 or requester_hour>=8 then
  return jsonb_build_object('errorCode','IDENTITY_RATE_LIMIT',
   'message','Too many verification requests. Please try again later.','statusCode',429,'retryAfter',3600);
 end if;
 update private.tvtms_qr_identity_challenges set status='expired'
  where ticket_id=citation.id and status='pending';
 insert into private.tvtms_qr_identity_challenges(ticket_id,token_hash,code_hash,requester_hash,expires_at)
   values(citation.id,p_token_hash,p_code_hash,p_requester_hash,current_timestamp+interval '10 minutes');
 return jsonb_build_object('status','created','ticketNumber',citation.ticket_number,
  'recipient',recipient,'expiresIn',600,'resendAfter',90);
end; $fn$;

create or replace function public.tvtms_qr_identity_delivery(
 p_token_hash text,p_delivery_status text
) returns jsonb language plpgsql security invoker set search_path='' as $fn$
declare challenge private.tvtms_qr_identity_challenges%rowtype;
begin
 if coalesce(p_token_hash,'') !~ '^[0-9a-f]{64}$'
    or coalesce(p_delivery_status,'') not in ('accepted','failed') then
   return jsonb_build_object('errorCode','VALIDATION_ERROR','message','Invalid email result.','statusCode',400);
 end if;
 select * into challenge from private.tvtms_qr_identity_challenges
  where token_hash=p_token_hash for update;
 if not found or challenge.status<>'pending' or challenge.delivery_status<>'pending' then
  return jsonb_build_object('errorCode','IDENTITY_VERIFICATION_UNAVAILABLE',
   'message','Verification is unavailable. Request a new code later.','statusCode',409);
 end if;
 update private.tvtms_qr_identity_challenges set
  delivery_status=p_delivery_status,delivered_at=current_timestamp,
  status=case when p_delivery_status='failed' then 'locked' else status end
 where id=challenge.id;
 return jsonb_build_object('status',p_delivery_status);
end; $fn$;

create or replace function public.tvtms_qr_identity_verify(
 p_ticket text,p_token_hash text,p_code_hash text
) returns jsonb language plpgsql security invoker set search_path='' as $fn$
declare challenge private.tvtms_qr_identity_challenges%rowtype;
 citation public.tickets%rowtype;
 remaining integer;
 driver_name text;
begin
 if coalesce(p_ticket,'') !~ '^[A-Z0-9][A-Z0-9/-]{0,29}$'
  or coalesce(p_token_hash,'') !~ '^[0-9a-f]{64}$'
  or coalesce(p_code_hash,'') !~ '^[0-9a-f]{64}$' then
  return jsonb_build_object('errorCode','VALIDATION_ERROR','message','Invalid verification code.','statusCode',400);
 end if;
 select * into challenge from private.tvtms_qr_identity_challenges
  where token_hash=p_token_hash for update;
 if not found then
  return jsonb_build_object('errorCode','IDENTITY_VERIFICATION_FAILED','message','Verification failed. Request another code.','statusCode',400);
 end if;
 select * into citation from public.tickets
  where id=challenge.ticket_id and upper(trim(ticket_number))=p_ticket;
 if not found or challenge.delivery_status<>'accepted' or challenge.status<>'pending' then
  return jsonb_build_object('errorCode','IDENTITY_VERIFICATION_FAILED','message','Verification failed. Request another code.','statusCode',400);
 end if;
 if challenge.expires_at<=current_timestamp then
  update private.tvtms_qr_identity_challenges set status='expired' where id=challenge.id;
  return jsonb_build_object('errorCode','IDENTITY_EXPIRED','message','Code expired. Request a new code.','statusCode',410);
 end if;
 if challenge.code_hash<>p_code_hash then
  remaining:=greatest(0,challenge.attempts_remaining-1);
  update private.tvtms_qr_identity_challenges set attempts_remaining=remaining,
   status=case when remaining=0 then 'locked' else 'pending' end where id=challenge.id;
  return jsonb_build_object('errorCode','IDENTITY_CODE_INVALID',
   'message','Incorrect verification code.','statusCode',400,'attemptsRemaining',remaining);
 end if;
 update private.tvtms_qr_identity_challenges set status='used',used_at=current_timestamp
  where id=challenge.id;
 driver_name:=nullif(trim(concat_ws(' ',nullif(trim(citation.driver_first_name),''),
   nullif(trim(citation.driver_middle_name),''),
   nullif(trim(citation.driver_last_name),''))),'');
 return jsonb_build_object('verified',true,
  'ticketNumber',citation.ticket_number,
  'citedDriverName',coalesce(driver_name,'Not recorded'),
  'registeredOwnerName',coalesce(nullif(trim(citation.owner_name_at_issue),''),'Not recorded'));
end; $fn$;

